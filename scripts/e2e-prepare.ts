// Prepares the local Supabase stack and the Next.js build for the E2E suite.
//
// Run by `npm run pretest:e2e`, right after `npm run db:reset` and before
// `next build`. It:
//   0. refuses to run when the shell has a live Supabase URL or service-role key
//      exported (shell values beat .env.production.local in `next build`);
//   1. publishes every seed product (the seed ships them unpublished);
//   2. creates the E2E users: admin@e2e.test (admin) and user@e2e.test (not admin);
//   3. writes .env.production.local so `next build` and `next start` see the
//      local Supabase keys and the E2E flags;
//   4. deletes .next, so the build starts clean. Pages with `revalidate` also
//      keep their Supabase responses in .next/cache/fetch-cache (Next's Data
//      Cache), and a build would otherwise reuse those from the previous run
//      instead of reading the freshly reset database.
//
// The E2E suite runs against a production build, so caching and revalidation
// behave as they do on Vercel. Playwright's config loads .env.production.local
// too, so test code can read the same variables (for example the service key).
//
// Run with: node --experimental-strip-types scripts/e2e-prepare.ts
// (hence the explicit .ts extensions on the imports below).

import { rmSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { createClient, type SupabaseClient } from "@supabase/supabase-js";
import { assertShellHasNoLiveSupabase } from "./lib/assert-local-supabase.ts";
import { E2E_ADMIN_EMAIL, E2E_PASSWORD, E2E_USER_EMAIL } from "./lib/e2e-users.ts";
import { readLocalSupabaseEnv } from "./lib/local-supabase.ts";
import { ensureUser } from "./lib/users.ts";

const E2E_PORT = 3100;

const ENV_FILE = fileURLToPath(new URL("../.env.production.local", import.meta.url));
const NEXT_DIR = fileURLToPath(new URL("../.next", import.meta.url));

/** `supabase db reset` returns before PostgREST has reloaded its schema, so wait for it. */
async function waitForApi(service: SupabaseClient): Promise<void> {
  const deadline = Date.now() + 60_000;
  let lastError = "no response";
  while (Date.now() < deadline) {
    const { error } = await service.from("products").select("id", { head: true, count: "exact" });
    if (!error) return;
    lastError = error.message;
    await new Promise((resolve) => setTimeout(resolve, 1_000));
  }
  throw new Error(`The local Supabase API did not become ready: ${lastError}`);
}

async function main(): Promise<void> {
  assertShellHasNoLiveSupabase("scripts/e2e-prepare.ts");

  const local = readLocalSupabaseEnv();
  const service = createClient(
    local.NEXT_PUBLIC_SUPABASE_URL,
    local.SUPABASE_SERVICE_ROLE_KEY,
    { auth: { persistSession: false, autoRefreshToken: false } },
  );
  await waitForApi(service);

  const published = await service
    .from("products")
    .update({ published: true })
    .eq("published", false)
    .select("slug");
  if (published.error) throw new Error(`Could not publish products: ${published.error.message}`);
  console.log(`e2e-prepare: published ${published.data.length} seed products`);

  await ensureUser(service, E2E_ADMIN_EMAIL, E2E_PASSWORD, { admin: true });
  await ensureUser(service, E2E_USER_EMAIL, E2E_PASSWORD, { admin: false });
  console.log(`e2e-prepare: users ${E2E_ADMIN_EMAIL} (admin) and ${E2E_USER_EMAIL} ready`);

  const env: Record<string, string> = {
    NEXT_PUBLIC_SUPABASE_URL: local.NEXT_PUBLIC_SUPABASE_URL,
    NEXT_PUBLIC_SUPABASE_ANON_KEY: local.NEXT_PUBLIC_SUPABASE_ANON_KEY,
    SUPABASE_SERVICE_ROLE_KEY: local.SUPABASE_SERVICE_ROLE_KEY,
    NEXT_PUBLIC_SITE_URL: `http://localhost:${E2E_PORT}`,
    ALLOW_DEV_FALLBACKS: "true",
    IP_HASH_SALT: "e2e",
    // A made-up ID so the analytics spec can check where the tag loads; it stubs Google's script.
    NEXT_PUBLIC_GA_MEASUREMENT_ID: "G-E2ETEST123",
  };
  const lines = Object.entries(env).map(([name, value]) => `${name}=${value}`);
  writeFileSync(ENV_FILE, `# Generated by scripts/e2e-prepare.ts. Local Supabase only; never commit.\n${lines.join("\n")}\n`);
  console.log("e2e-prepare: wrote .env.production.local");

  rmSync(NEXT_DIR, { recursive: true, force: true });
  console.log("e2e-prepare: cleared .next");
}

main().catch((error: unknown) => {
  console.error(error);
  process.exit(1);
});
